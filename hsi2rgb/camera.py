"""ハイパースペクトルカメラ AG-HSV10M（Panasonic）の仕様値。

ここに書いてあるのは「カメラとマスクで決まる定数」だけ。
撮影内容や解析の好みで変えるパラメータは config.py に置く。

--- カメラの概要（取扱説明書 DVQP3478 より）-------------------------------
    型式          : レンズ交換式デジタル一眼（マイクロフォーサーズマウント）
    撮像素子      : Sony IMX535, 1/1.1" モノクロ CMOS, グローバルシャッター
    画素サイズ    : 2.74 um 角 / 有効 約1105万画素
    画像サイズ    : 高解像度モード 3840x2160 / 高感度モード 1920x1440(FHD)
    圧縮方式      : 圧縮センシング方式（ランダムフィルター + 画像復元）
    波長範囲      : 420-700 nm（29バンド）/ 600-900 nm（31バンド）
                    ※バンドパスフィルターで切り替え
    FWHM          : 10 nm
    記録形式      : ハイパースペクトルカメラ専用 RAW ファイル

センサは「モノクロ1枚」しか撮らない。画素ごとに透過スペクトルが違う
ランダムフィルター（マスク）越しに撮り、付属ソフト Iromiel Hyper が
圧縮センシングで29バンドに復元する。つまり
    センサが記録するもの : 計測画像 y (H, W)  … 全バンドがマスク越しに混ざった1枚
    復元して得るもの     : バンド画像 x (29, H, W)
"""

# --- A/D と黒レベル --------------------------------------------------------
# RAW の値域は 0〜4095（実測で最大値がちょうど 4095）。
SENSOR_BIT_DEPTH = 12

# 黒レベル（ペデスタル）。camera/compressed_*.png は RAW からこの値が引かれている。
# 検証済みペアで全画素の差がぴったり 128 だった（例外なし）。
#     compressed = RAW - 128
# したがって飽和値は RAW が 4095、compressed が 3967 になる。
# 読み込み時に足し戻して「センサDN空間（0〜4095）」に揃えるのが本プロジェクトの約束。
SENSOR_BLACK_LEVEL = 128

# --- RAW ファイルの構造（実測で確定）--------------------------------------
#   128 バイト   ヘッダ … 幅(0x0780=1920)・高さ(0x05a0=1440)・"AG-HSV10M"・"K5NQA0013" など
#   W*H*2 バイト データ … uint16 リトルエンディアン、値域 0〜4095
#   384 バイト   末尾   … ゼロ埋め
# ファイル全体は 128 + W*H*2 + 384 = 5,530,112 バイト（FHD の場合）。
# 偶然 512 + W*H*2 とも一致するが、512 で読むと画像が 192 画素ずれる。
RAW_HEADER_BYTES = 128
RAW_WIDTH_FHD = 1920
RAW_HEIGHT_FHD = 1440

# --- バンド構成 ------------------------------------------------------------
# 420-700 nm を 29 バンド（10 nm 刻み）。
BAND_START_NM = 420
BAND_STEP_NM = 10
BAND_COUNT = 29
BAND_WAVELENGTHS_NM = [BAND_START_NM + BAND_STEP_NM * i for i in range(BAND_COUNT)]

# 600-900 nm 31 バンド（別フィルター。現在の変換では未使用）
BAND_START_NM_NIR = 600
BAND_COUNT_NIR = 31


def sensor_full_scale(bit_depth=SENSOR_BIT_DEPTH):
    """センサの A/D 分解能に対するフルスケール（2^bit - 1）を返す。"""
    if not isinstance(bit_depth, int) or not 1 <= bit_depth <= 16:
        raise ValueError(f"bit_depth は 1〜16 の整数である必要があります: {bit_depth}")
    return float((1 << bit_depth) - 1)


SENSOR_FULL_SCALE = sensor_full_scale(SENSOR_BIT_DEPTH)
